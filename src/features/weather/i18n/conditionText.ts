export function conditionText(
  condition: WeatherCondition,
  language: WeatherLanguage,
  isDay: boolean,
) {
  if (language === 'en') return condition.text
  if (condition.code === 1000 && !isDay) return 'صاف'
  return persianConditions[condition.code] ?? condition.text
}
